function referenceFor(platform,command){
 if(command.startsWith('git '))return references.git;
 if(command.startsWith('docker '))return references.docker;
 if(command.startsWith('kubectl '))return references.kubernetes;
 if(command.startsWith('brew '))return references.brew;
 if(command.startsWith('npm '))return references.npm;
 if(command.startsWith('python '))return references.python;
 if(/^(ssh|sftp|scp|ssh-keygen)\b/.test(command))return references.ssh;
 if(command.startsWith('sqlite3 '))return references.sqlite;
 if(command.startsWith('redis-cli '))return references.redis;
 if(/^(sudo )?(systemctl|journalctl)\b/.test(command))return references.systemd;
 return references[platform]||references.linux;
}
