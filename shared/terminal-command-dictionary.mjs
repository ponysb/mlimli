export function filterCommands(items,{platform='all',category='all',query=''}={}){
 const terms=query.trim().toLowerCase().split(/\s+/).filter(Boolean);
 return items.filter(item=>(!item.builtin||matchesPlatform(item,platform))&&(category==='all'||item.tag===category)&&terms.every(term=>`${item.name} ${item.command} ${item.tag||''} ${item.keywords||''} ${item.description||''}`.toLowerCase().includes(term)));
}
export function quoteParameter(value,shell='unix'){
 const text=String(value);if(/[\x00-\x1f\x7f]/.test(text))throw Error('参数不能包含换行或控制字符');
 if(shell==='cmd'){if(/["%!^&|<>]/.test(text))throw Error('CMD 参数不支持引号、变量展开和控制符，请改用 PowerShell 或手动编辑');return `"${text}"`;}
 return shell==='powershell'?`'${text.replaceAll("'","''")}'`:`'${text.replaceAll("'","'\\''")}'`;
}
