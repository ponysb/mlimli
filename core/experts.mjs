export const EXPERTS = definitions.map(([id, name, category, description, tags, prompt]) => ({ id, name, category, description, tags, prompt }));
let platformExperts = [];
export function setPlatformExperts(items) {
  platformExperts = items.filter((item) => item.kind === 'expert').map((item) => ({ id: `platform-${item.id}`, name: item.name, category: item.category || '平台', description: item.description || '', tags: item.tags || [], prompt: item.content, platform: true }));
}
function localFile() { return path.join(agentDataDir(), 'experts.json'); }
export function listExperts() {
  let local = [];
  try { local = JSON.parse(fs.readFileSync(localFile(), 'utf8')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  return [...platformExperts, ...(Array.isArray(local) ? local : []).map((item) => ({ ...item, local: true }))];
}
export function getExpert(id) { return listExperts().find((expert) => expert.id === id) || null; }
export function saveExpert(value) {
  const name = String(value?.name || '').trim().slice(0, 80);
  const prompt = String(value?.prompt || '').trim().slice(0, 30000);
  if (!name || !prompt) throw new Error('专家名称和提示词不能为空');
  const local = listExperts().filter((item) => item.local);
  const id = value.id || `local-${crypto.randomUUID()}`;
  if (value.id && !local.some((item) => item.id === id)) throw new Error('只能编辑本地专家');
  const item = { id, name, prompt, category: String(value.category || '自建').trim().slice(0, 40), description: String(value.description || '').trim().slice(0, 300), tags: Array.isArray(value.tags) ? value.tags.map((tag) => String(tag).slice(0, 30)).slice(0, 8) : [], local: true };
  fs.writeFileSync(localFile(), JSON.stringify([...local.filter((entry) => entry.id !== id), item], null, 2));
  return item;
}
export function deleteExpert(id) {
  const local = listExperts().filter((item) => item.local);
  if (!local.some((item) => item.id === id)) throw new Error('只能删除本地专家');
  fs.writeFileSync(localFile(), JSON.stringify(local.filter((item) => item.id !== id), null, 2));
}
